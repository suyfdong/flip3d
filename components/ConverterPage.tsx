type Status = "idle" | "loading" | "converting" | "error";

/**
 * Optional rich on-page content for a converter landing. Lets a high-value
 * page (e.g. /3mf-to-stl) carry a tuned lede, format-specific body, FAQ, and
 * extra internal links to capture its keyword-variant cluster — while the
 * other routes keep the lean default. All fields are plain serializable data
 * so this passes cleanly from a server route into this client component.
 */
export type ConverterContent = {
  lede?: string;
  aboutTitle?: string;
  about?: string[];
  faq?: { q: string; a: string }[];
  related?: { href: string; title: string; desc: string }[];
  /** Override the displayed source-format label (e.g. "STP" on /stp-to-stl,
   * which parses as the "step" format). Does not change parsing. */
  fromLabel?: string;
};

// Every source format has a viewer page; point converters at it so users can
// inspect the file first (and so the viewer pages get contextual links).
const VIEWER_BLURB: Partial<Record<Format, string>> = {
  "3mf": "See plates, filament colors and parts",
  ply: "Point clouds, scan colors and splat previews",
  step: "Assembly tree, part colors and measuring",
  iges: "Part list, colors and measuring",
};

function viewerLink(from: Format, fromLabel: string): { href: string; title: string; desc: string } {
  const href = from === "step" && fromLabel === "STP" ? "/stp-viewer/" : VIEWER_PATH_BY_FORMAT[from];
  return {
    href,
    title: `${fromLabel} Viewer`,
    desc: VIEWER_BLURB[from] ?? `Open and inspect the ${fromLabel} file in 3D`,
  };
}

type Props = {
  from: Format;
  to: Format;
  content?: ConverterContent;
};

/**
 * One true sentence per format about what it actually stores.
 *
 * The lean converter pages used to carry three canned answers that were
 * word-for-word identical on every route — which is precisely the footprint of
 * autogenerated content. Composing each answer out of the source and target
 * traits means /glb-to-ply and /step-to-stl say different, checkable things,
 * while every claim stays tied to what the parsers and exporters actually do.
 */
const SOURCE_TRAITS: Record<Format, string> = {
  stl:
    "An STL is a bare triangle list — no units, no colour, no material, and every triangle repeats its own copy of its three vertices.",
  obj:
    "OBJ is plain text: vertex positions, normals, UVs and faces. Materials live in a separate .mtl file that has to travel next to it.",
  glb:
    "GLB is binary glTF — geometry plus PBR materials and textures in one file, with metres as its implied unit.",
  "3mf":
    "3MF is a ZIP of XML with a declared unit and optional colour/material extensions. Bambu Studio and OrcaSlicer save projects with the production extension, where the geometry sits in separate object files instead of the root model.",
  ply:
    "PLY can carry arbitrary per-vertex properties, which is how scans and Gaussian splats store their colour. A PLY with no faces is a point cloud rather than a surface.",
  step:
    "STEP is B-rep CAD data — exact curves and analytic surfaces rather than triangles.",
  iges:
    "IGES is an older CAD interchange format of surfaces and curves, and the faces in a real IGES often don't join up perfectly.",
  fbx:
    "FBX comes from DCC tools and carries a scene graph, materials, textures and often animation on top of the geometry.",
  dae:
    "DAE (Collada) is an XML scene format: hierarchy, materials and geometry in one document.",
  usdz:
    "USDZ is Apple's binary USD package — scene graph plus textures, built to be opened in place.",
  wrl:
    "WRL (VRML 2.0) is an old scene description format: geometry, normals and flat per-object colour rather than textures.",
};

// Only the five writable mesh formats are ever a conversion target; the rest
// are read-only sources, so this map is deliberately partial.
const TARGET_TRAITS: Partial<Record<Format, string>> = {
  stl:
    "The STL written here is binary triangles with normals — no unit field (slicers assume millimetres), no colour and no material.",
  obj:
    "The OBJ written here keeps vertices, normals, UVs and faces, but no .mtl is written, so materials and vertex colours don't come along.",
  glb:
    "The GLB written here is the richest output: it keeps materials when the source has them and stores vertex colours as COLOR_0.",
  "3mf":
    'The 3MF written here is core-spec with unit="millimeter" and geometry only — the optional 3MF colour and material extensions are not written.',
  ply:
    "The PLY written here is binary and keeps vertex colours when the mesh has them, which makes it the right output for scans and coloured heightmaps.",
};

/** Details that only apply to a specific format pair. */
function pairNote(from: Format, to: Format): string {
  if (from === "step" || from === "iges") {
    return " The file is triangulated on import, so precise surfaces become flat facets — that is what makes it openable in a browser at all, and it means the result is a mesh, never editable CAD.";
  }
  if (from === "3mf") {
    return " Bambu and Orca projects are flattened first: the production-extension object files are merged into a single model before reading, so a MakerWorld download converts instead of appearing empty.";
  }
  if (from === "ply" && (to === "stl" || to === "3mf")) {
    return " If that PLY turns out to have no faces it is a point cloud, and there is no surface to turn into a solid — the tool tells you so instead of writing an empty file.";
  }
  return "";
}

/** Units are the most common reason a converted model prints at the wrong size. */
function sizeAnswer(from: Format, to: Format): string {
  if (from === "glb") {
    return "Not at the same scale. glTF counts in metres and no step here rescales the numbers, so a GLB authored one unit wide comes out one millimetre — 1000× too small. Scale it to a measured length in the STL Editor before you print.";
  }
  if (to === "glb") {
    return "The numbers are copied unchanged, and glTF counts in metres — so a 100 mm model arrives as 100 units, which a unit-aware app like Blender reads as 100 metres. Scale it on import if it's going into a glTF-native pipeline.";
  }
  if (to === "3mf") {
    return "Yes. 3MF declares its unit and this writer states millimetres, so a slicer reads the model at its real dimensions instead of guessing.";
  }
  if (from === "3mf") {
    return "The numbers are copied unchanged, and STL, OBJ and PLY have no unit field — slicers read them as millimetres. A 3MF saved in millimetres comes out exact; one authored in inches or centimetres comes out 25.4× or 10× too small until you rescale it.";
  }
  return "Only if the file was authored in millimetres. STL, OBJ and PLY carry no unit at all — slicers assume millimetres — so a model built in inches arrives 25.4× too small. Resize it to a measured length in the STL Editor before printing.";
}

/** Why a read-only format stays read-only, phrased for what it actually carries. */
function readOnlyReason(from: Format): string {
  if (from === "step" || from === "iges") {
    return "the curve and surface data the format exists to carry";
  }
  return "the materials and scene data that make the format worth using";
}

function buildBaselineFaq(
  from: Format,
  to: Format,
  fromLabel: string,
  toLabel: string,
): { q: string; a: string }[] {
  const sourceOnly = SOURCE_ONLY_FORMATS.has(from);
  const targetTrait =
    TARGET_TRAITS[to] ?? `Flip3D writes the geometry out as a ${toLabel} mesh.`;
  const faq = [
    {
      q: `How do I convert ${fromLabel} to ${toLabel}?`,
      a: `Drop your ${fromLabel} file into the box above, check the result in the 3D preview, then click Convert & Download .${to}. The whole conversion runs in your browser, so there is nothing to install and nothing to upload.`,
    },
    {
      q: `What changes when my ${fromLabel} becomes a ${toLabel}?`,
      a: `${SOURCE_TRAITS[from]} ${targetTrait} Flip3D parses the file into a triangle mesh on your device and writes the triangles back out unchanged — no re-meshing and no simplification.${pairNote(from, to)}`,
    },
    {
      q: `Will the converted ${toLabel} be the right size?`,
      a: sizeAnswer(from, to),
    },
  ];
  if (sourceOnly) {
    faq.push({
      q: `Can I convert ${toLabel} back to ${fromLabel}?`,
      a: `No — ${fromLabel} is read-only here. Flip3D can open ${fromLabel} files and write ${toLabel}, but it does not write ${fromLabel}. That limit is deliberate: a writer would have to reproduce ${readOnlyReason(from)}, and emitting bare triangles under a .${from} extension would hand you a file that opens and then loses the very thing you converted it for.`,
    });
  }
  faq.push({
    q: `Is there a free ${fromLabel} to ${toLabel} converter with no signup?`,
    a: `This is one. No account, no email step, no watermark, no file-size paywall, and nothing to install — drop the file and download the ${toLabel}. The conversion runs in WebGL on Windows, macOS, Linux, ChromeOS and mobile.`,
  });
  return faq;
}

export default function ConverterPage({ from, to, content }: Props) {
  const fromLabel = content?.fromLabel ?? FORMAT_LABELS[from];
  const toLabel = FORMAT_LABELS[to];

  // Rich routes supply their own FAQ *and* their own FAQPage JSON-LD, so only
  // the lean routes get the generated block — otherwise the page would carry
  // two FAQPage schemas.
  const faqItems =
    content?.faq && content.faq.length > 0
      ? content.faq
      : buildBaselineFaq(from, to, fromLabel, toLabel);
  const emitFaqSchema = !(content?.faq && content.faq.length > 0);

  const [object, setObject] = useState<THREE.Object3D | null>(null);
  const [fileName, setFileName] = useState("");
  const [status, setStatus] = useState<Status>("idle");
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Dispose the loaded Object3D when it changes or on unmount.
  // Without this, navigating away (clicking the logo, jumping to another
  // landing page) leaks the geometry + material + GPU buffers and stalls
  // the next page's MeshViewer initialization.
  useEffect(() => {
    return () => {
      if (object) disposeObject(object);
    };
  }, [object]);

  const handleFile = async (
    buffer: ArrayBuffer,
    name: string,
    source: "drop" | "sample" | "url" = "drop",
  ) => {
    setStatus("loading");
    setErrorMsg(null);
    try {
      const parsed = await parseToObject(buffer, from);
      // The useEffect cleanup will dispose the previous object when state updates.
      setObject(parsed);
      setFileName(name);
      setStatus("idle");
      trackFileUploaded(from, source);
    } catch (err) {
      console.error("Parse failed", err);
      setErrorMsg(err instanceof Error ? err.message : `Could not parse .${from} file`);
      setStatus("error");
    }
  };

  const handleSample = async () => {
    setStatus("loading");
    setErrorMsg(null);
    trackSampleLoaded(from);
    try {
      const geo = new THREE.TorusKnotGeometry(10, 3, 100, 16);
      const mat = new THREE.MeshStandardMaterial({
        color: 0x3b82f6,
        metalness: 0.1,
        roughness: 0.6,
      });
      const sampleMesh = new THREE.Mesh(geo, mat);
      const blob = await exportToBlob(sampleMesh, from);
      geo.dispose();
      mat.dispose();
      const buffer = await blob.arrayBuffer();
      await handleFile(buffer, `flip3d-sample.${from}`, "sample");
    } catch (err) {
      console.error("Sample failed", err);
      setErrorMsg(err instanceof Error ? err.message : "Failed to load sample");
      setStatus("error");
    }
  };

  const handleReset = () => {
    setObject(null);
    setFileName("");
    setStatus("idle");
    setErrorMsg(null);
  };

  const handleConvert = async () => {
    if (!object) return;
    setStatus("converting");
    setErrorMsg(null);
    try {
      const blob = await exportToBlob(object, to);
      const baseName = fileName.replace(/\.[^.]+$/, "") || "model";
      downloadBlob(blob, `${baseName}.${to}`);
      setStatus("idle");
      trackFileConverted(from, to);
    } catch (err) {
      console.error("Convert failed", err);
      const msg = err instanceof Error ? err.message : "Conversion failed";
      setErrorMsg(msg);
      setStatus("error");
      trackConvertError(from, to, msg);
    }
  };

  const reverseExists = !SOURCE_ONLY_FORMATS.has(from);
  const reverseSlug = reverseExists ? `/${to}-to-${from}/` : "/";
  const reverseLabel = reverseExists
    ? `${toLabel} → ${fromLabel}`
    : "All conversions";
  const reverseHint = reverseExists
    ? "Go the other way"
    : `${fromLabel} is read-only in Flip3D — we import it but don't write it back. Browse other conversions.`;

  return (
    <>
      <UrlParamLoader
        onStart={() => {
          setStatus("loading");
          setErrorMsg(null);
        }}
        onLoaded={(buffer, name) => handleFile(buffer, name, "url")}
        onError={(m) => {
          setErrorMsg(m);
          setStatus("error");
        }}
      />
      <section className="max-w-6xl mx-auto px-4 sm:px-6 pt-10 pb-8 sm:pt-12">
        {!object ? (
          <>
            <div className="text-center max-w-3xl mx-auto mb-10">
              <p className="text-sm font-medium text-blue-600 dark:text-blue-400 mb-3 uppercase tracking-wide">
                Free Online Converter
              </p>
              <h1 className="text-3xl sm:text-4xl lg:text-5xl font-bold tracking-tight mb-4">
                Convert{" "}
                <span className="bg-gradient-to-r from-blue-500 to-cyan-500 bg-clip-text text-transparent">
                  {fromLabel} to {toLabel}
                </span>
              </h1>
              <p className="text-lg text-zinc-600 dark:text-zinc-400">
                {content?.lede ??
                  `Drop a .${from} file, get a .${to} back in seconds. Runs entirely in your browser — no upload, no signup, no watermark.`}
              </p>
            </div>

            <div className="max-w-2xl mx-auto">
              <Dropzone
                onFileLoaded={handleFile}
                accept={
                  from === "step"
                    ? [".step", ".stp"]
                    : from === "iges"
                      ? [".iges", ".igs"]
                      : from === "glb"
                        ? [".glb", ".gltf"]
                        : from === "wrl"
                          ? [".wrl", ".vrml"]
                          : [`.${from}`]
                }
              />

              {!SOURCE_ONLY_FORMATS.has(from) && (
                <div className="mt-4 flex items-center justify-center gap-2 text-sm">
                  <span className="text-zinc-500 dark:text-zinc-400">
                    No .{from} handy?
                  </span>
                  <button
                    onClick={handleSample}
                    disabled={status === "loading"}
                    className="px-3 py-1 rounded-full font-mono text-xs uppercase border border-zinc-300 dark:border-zinc-700 hover:border-blue-400 hover:bg-blue-50 dark:hover:bg-blue-950/30 hover:text-blue-700 dark:hover:text-blue-300 transition-colors disabled:opacity-50"
                  >
                    Try a sample .{from}
                  </button>
                </div>
              )}

              {status === "loading" && (
                <div className="mt-4 px-4 py-3 rounded-lg bg-zinc-100 dark:bg-zinc-900 text-sm text-zinc-700 dark:text-zinc-300">
                  Parsing file…
                </div>
              )}

              {errorMsg && (
                <div className="mt-4 px-4 py-3 rounded-lg bg-red-50 dark:bg-red-950/30 text-red-700 dark:text-red-300 text-sm">
                  ⚠️ {errorMsg}
                </div>
              )}
            </div>
          </>
        ) : (
          <>
            <div className="flex items-center justify-between mb-4 flex-wrap gap-3">
              <div>
                <h1 className="text-2xl font-semibold tracking-tight">{fileName}</h1>
                <p className="text-sm text-zinc-500 dark:text-zinc-400 mt-1">
                  Drag to rotate · scroll to zoom
                </p>
              </div>
              <button
                onClick={handleReset}
                className="px-4 py-2 text-sm rounded-lg border border-zinc-300 dark:border-zinc-700 hover:bg-zinc-100 dark:hover:bg-zinc-900"
              >
                ← Load another .{from}
              </button>
            </div>

            <div className="rounded-xl border border-blue-200 dark:border-blue-900 bg-blue-50/50 dark:bg-blue-950/20 p-4 mb-4 flex items-center justify-between gap-4 flex-wrap">
              <div className="flex items-center gap-3 text-sm flex-wrap">
                <span className="font-mono uppercase px-2 py-0.5 rounded bg-white dark:bg-zinc-900 border border-zinc-200 dark:border-zinc-800 text-xs">
                  {fromLabel}
                </span>
                <span className="text-zinc-500">→</span>
                <span className="font-mono uppercase px-2 py-0.5 rounded bg-white dark:bg-zinc-900 border border-zinc-200 dark:border-zinc-800 text-xs">
                  {toLabel}
                </span>
              </div>
              <button
                onClick={handleConvert}
                disabled={status === "converting"}
                className="px-5 py-2 text-sm font-medium rounded-lg bg-gradient-to-r from-blue-500 to-cyan-500 text-white hover:opacity-90 disabled:opacity-50 disabled:cursor-not-allowed"
              >
                {status === "converting"
                  ? "Converting…"
                  : `Convert & Download .${to}`}
              </button>
            </div>

            {errorMsg && (
              <div className="mb-4 px-4 py-3 rounded-lg bg-red-50 dark:bg-red-950/30 text-red-700 dark:text-red-300 text-sm">
                ⚠️ {errorMsg}
              </div>
            )}

            <div className="h-[60vh] sm:h-[480px] lg:h-[560px]">
              <MeshViewer object={object} />
            </div>

            <div className="mt-4 rounded-xl border border-zinc-200 dark:border-zinc-800 bg-zinc-50 dark:bg-zinc-900/50 p-4 flex items-center justify-between gap-3 flex-wrap">
              <div className="text-sm text-zinc-600 dark:text-zinc-400">
                <span className="font-medium text-zinc-900 dark:text-zinc-100">
                  Want to embed a viewer on your site?
                </span>{" "}
                One line of iframe HTML, 4 themes, free forever.
              </div>
              <Link
                href="/embed/"
                className="px-4 py-2 text-sm font-medium rounded-lg border border-blue-300 dark:border-blue-800 text-blue-700 dark:text-blue-300 hover:bg-blue-50 dark:hover:bg-blue-950/30 whitespace-nowrap"
              >
                Embed viewer →
              </Link>
            </div>
          </>
        )}
      </section>

      {!object && (
        <>
          <AdSlot />
          <section className="border-t border-zinc-200 dark:border-zinc-800 py-14">
            <div className="max-w-3xl mx-auto px-4 sm:px-6">
              <h2 className="text-2xl font-bold tracking-tight mb-6">
                How to convert {fromLabel} to {toLabel}
              </h2>
              <ol className="space-y-3 text-zinc-700 dark:text-zinc-300 list-decimal pl-6">
                <li>
                  Drag your <code className="font-mono text-sm">.{from}</code>{" "}
                  file into the box above (or click to browse).
                </li>
                <li>
                  Preview the model in the viewer — drag to rotate, scroll to
                  zoom.
                </li>
                <li>
                  Click <strong>Convert &amp; Download .{to}</strong>. The{" "}
                  <code className="font-mono text-sm">.{to}</code> file lands in
                  your downloads folder.
                </li>
              </ol>
              <p className="text-sm text-zinc-500 dark:text-zinc-400 mt-6">
                Conversion runs in your browser via{" "}
                <code className="font-mono">three.js</code>. Your file never
                leaves your device — there&apos;s no upload, no server, and
                nothing is stored.
              </p>
            </div>
          </section>

          {content?.about && content.about.length > 0 && (
            <section className="border-t border-zinc-200 dark:border-zinc-800 py-14 bg-zinc-50 dark:bg-zinc-950/50">
              <div className="max-w-3xl mx-auto px-4 sm:px-6">
                <h2 className="text-2xl font-bold tracking-tight mb-5">
                  {content.aboutTitle ?? `About ${fromLabel} → ${toLabel}`}
                </h2>
                <div className="space-y-4 text-zinc-700 dark:text-zinc-300 leading-relaxed">
                  {content.about.map((p, i) => (
                    <p key={i}>{p}</p>
                  ))}
                </div>
              </div>
            </section>
          )}

          {faqItems.length > 0 && (
            <section className="border-t border-zinc-200 dark:border-zinc-800 py-14">
              {emitFaqSchema && <JsonLd data={faqPageSchema(faqItems)} />}
              <div className="max-w-3xl mx-auto px-4 sm:px-6">
                <h2 className="text-2xl font-bold tracking-tight mb-5">
                  Frequently asked questions
                </h2>
                <div className="divide-y divide-zinc-200 dark:divide-zinc-800 border-y border-zinc-200 dark:border-zinc-800">
                  {faqItems.map((f) => (
                    <details key={f.q} className="group py-4">
                      <summary className="flex cursor-pointer items-center justify-between font-medium list-none">
                        {f.q}
                        <span className="ml-4 text-zinc-400 transition-transform group-open:rotate-45">
                          +
                        </span>
                      </summary>
                      <p className="mt-3 text-zinc-600 dark:text-zinc-400 leading-relaxed">
                        {f.a}
                      </p>
                    </details>
                  ))}
                </div>
              </div>
            </section>
          )}

          <section className="border-t border-zinc-200 dark:border-zinc-800 py-14 bg-zinc-50 dark:bg-zinc-950/50">
            <div className="max-w-3xl mx-auto px-4 sm:px-6">
              <h2 className="text-xl font-bold tracking-tight mb-4">
                Related converters
              </h2>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                {[
                  ...(content?.related ?? []),
                  ...(content?.related?.some((r) => r.href === viewerLink(from, fromLabel).href)
                    ? []
                    : [viewerLink(from, fromLabel)]),
                ].map((r) => (
                  <Link
                    key={r.href}
                    href={r.href}
                    className="block px-5 py-4 rounded-xl border border-zinc-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 hover:border-blue-400 dark:hover:border-blue-700 transition-colors"
                  >
                    <div className="font-semibold">{r.title}</div>
                    <div className="text-sm text-zinc-500 dark:text-zinc-400 mt-1">
                      {r.desc}
                    </div>
                  </Link>
                ))}
                <Link
                  href={reverseSlug}
                  className="block px-5 py-4 rounded-xl border border-zinc-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 hover:border-blue-400 dark:hover:border-blue-700 transition-colors"
                >
                  <div className="font-semibold">{reverseLabel}</div>
                  <div className="text-sm text-zinc-500 dark:text-zinc-400 mt-1">
                    {reverseHint}
                  </div>
                </Link>
                <Link
                  href="/embed/"
                  className="block px-5 py-4 rounded-xl border border-zinc-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 hover:border-blue-400 dark:hover:border-blue-700 transition-colors"
                >
                  <div className="font-semibold">Embed viewer →</div>
                  <div className="text-sm text-zinc-500 dark:text-zinc-400 mt-1">
                    One line of iframe HTML on your site
                  </div>
                </Link>
                <Link
                  href="/"
                  className="block px-5 py-4 rounded-xl border border-zinc-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 hover:border-blue-400 dark:hover:border-blue-700 transition-colors"
                >
                  <div className="font-semibold">All Tools</div>
                  <div className="text-sm text-zinc-500 dark:text-zinc-400 mt-1">
                    Convert any of 4 formats to any other
                  </div>
                </Link>
              </div>
            </div>
          </section>
        </>
      )}
    </>
  );
}
